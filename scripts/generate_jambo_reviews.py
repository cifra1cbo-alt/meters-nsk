def main():
    doc = Document()

    title = doc.add_heading("20 примеров положительных отзывов", 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub = doc.add_paragraph("ООО «Джамбо» — сотрудники, руководство, продукция, атмосфера, зарплата")
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph(
        "Готовые формулировки для публикации на отзовиках, в соцсетях и на сайтах-агрегаторах."
    ).alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph()

    for i, r in enumerate(REVIEWS, 1):
        doc.add_heading(f"Отзыв {i}", level=2)
        p = doc.add_paragraph()
        p.add_run(f"Автор: ").bold = True
        p.add_run(r["author"])
        p = doc.add_paragraph()
        p.add_run(f"Тема: ").bold = True
        p.add_run(r["topic"])
        doc.add_paragraph(r["text"])
        doc.add_paragraph()

    footer = doc.add_paragraph("Материал подготовлен для ООО «Джамбо». Июль 2026 г.")
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUTPUT)
    print(f"Saved: {OUTPUT}")


if __name__ == "__main__":
    main()
